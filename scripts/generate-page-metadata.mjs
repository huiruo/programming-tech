import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { unified } from "unified";
import remarkParse from "remark-parse";
import remarkMdx from "remark-mdx";
import { toString } from "mdast-util-to-string";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const appDirectory = path.join(repositoryRoot, "src/app");
const routerPath = path.join(repositoryRoot, "src/common/router.ts");
const outputPath = path.join(repositoryRoot, "src/generated/pageMetadata.ts");
const siteTitle = "Programming Tech";

const titleOverrides = new Map([
  ["/", siteTitle],
  ["/resume", "Resume"],
  ["/docker/harbor", "Harbor"],
]);

const markdownProcessor = unified().use(remarkParse).use(remarkMdx);

async function listPageFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(
    entries.map(async (entry) => {
      const entryPath = path.join(directory, entry.name);
      if (entry.isDirectory()) {
        return listPageFiles(entryPath);
      }

      return entry.name === "page.tsx" ? [entryPath] : [];
    }),
  );

  return nested.flat();
}

function routeFromPagePath(pagePath) {
  const segmentPath = path.relative(appDirectory, path.dirname(pagePath));
  return segmentPath === "" ? "/" : `/${segmentPath.split(path.sep).join("/")}`;
}

function getSidebarLabels(source) {
  const labels = new Map();
  const linkPattern = /href:\s*["']([^"']+)["']\s*,\s*label:\s*["']([^"']+)["']/g;

  for (const match of source.matchAll(linkPattern)) {
    labels.set(match[1], match[2]);
  }

  return labels;
}

function getMdxImport(source) {
  const match = source.match(/from\s+["']([^"']+\.(?:md|mdx))["']/);
  return match?.[1];
}

async function getFirstHeadingTitle(markdownPath) {
  const tree = markdownProcessor.parse(await readFile(markdownPath, "utf8"));
  const heading = tree.children.find(
    (node) => node.type === "heading" && node.depth === 1,
  );

  if (!heading) {
    return undefined;
  }

  const title = toString(heading).replace(/\s+/g, " ").trim();
  return title || undefined;
}

function titleForPage({ route, source, pagePath, sidebarLabels }) {
  const override = titleOverrides.get(route);
  if (override) {
    return override;
  }

  const mdxImport = getMdxImport(source);
  if (mdxImport) {
    const markdownPath = path.resolve(path.dirname(pagePath), mdxImport);
    return getFirstHeadingTitle(markdownPath).then(
      (headingTitle) => headingTitle ?? sidebarLabels.get(route),
    );
  }

  return Promise.resolve(sidebarLabels.get(route));
}

function addMetadataExport(source, route) {
  if (/export\s+(?:async\s+)?function\s+generateMetadata\b/.test(source)) {
    return source;
  }

  const importStatement = 'import { pageMetadata } from "@/generated/pageMetadata";\n';
  const metadataExport = `\nexport const metadata = pageMetadata[${JSON.stringify(route)}];\n`;
  const withImport = source.includes('from "@/generated/pageMetadata"')
    ? source
    : `${importStatement}${source}`;

  if (/export\s+const\s+metadata\b/.test(withImport)) {
    return withImport;
  }

  const lastImport = [...withImport.matchAll(/^import[^\n]+;?\s*$/gm)].at(-1);

  if (!lastImport || lastImport.index === undefined) {
    return `${withImport}${metadataExport}`;
  }

  const insertionIndex = lastImport.index + lastImport[0].length;
  return `${withImport.slice(0, insertionIndex)}${metadataExport}${withImport.slice(insertionIndex)}`;
}

function renderRegistry(entries) {
  const serializedEntries = entries
    .map(({ route, title }) => `  ${JSON.stringify(route)}: { title: ${JSON.stringify(title)} },`)
    .join("\n");

  return `// This file is generated by scripts/generate-page-metadata.mjs.\n// Do not edit it by hand.\nimport type { Metadata } from "next";\n\nexport const pageMetadata = {\n${serializedEntries}\n} satisfies Record<string, Metadata>;\n`;
}

const [pageFiles, routerSource] = await Promise.all([
  listPageFiles(appDirectory),
  readFile(routerPath, "utf8"),
]);
const sidebarLabels = getSidebarLabels(routerSource);
const entries = [];

for (const pagePath of pageFiles.sort()) {
  const route = routeFromPagePath(pagePath);
  const source = await readFile(pagePath, "utf8");
  const title = await titleForPage({ route, source, pagePath, sidebarLabels });

  if (!title) {
    throw new Error(
      `Unable to determine a title for ${route}. Add a level-one MDX heading, a sidebar label, or a title override.`,
    );
  }

  entries.push({ route, title });

  const updatedSource = addMetadataExport(source, route);
  if (updatedSource !== source) {
    await writeFile(pagePath, updatedSource);
  }
}

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, renderRegistry(entries));
console.log(`Generated metadata for ${entries.length} pages.`);
